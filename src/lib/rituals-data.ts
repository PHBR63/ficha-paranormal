// Tipos de elementos disponíveis para rituais
export type RitualElement = 'sangue' | 'morte' | 'conhecimento' | 'energia' | 'medo';

// Interface para aprimoramentos de rituais
export interface RitualEnhancement {
  name: 'Discente' | 'Verdadeiro';
  cost: number; // PE adicional
  description: string;
  requirements?: string; // Ex: "Requer 2º círculo", "Requer afinidade"
}

// Interface principal para rituais
export interface Ritual {
  id: string;
  name: string;
  circle: number; // 1 a 4
  element: RitualElement;
  execution: string; // Padrão, Completa, Reação, etc.
  range: string;
  target?: string;
  area?: string;
  duration: string;
  resistance?: string;
  description: string;
  cost: number; // Custo base em PE
  enhancements?: RitualEnhancement[];
}

