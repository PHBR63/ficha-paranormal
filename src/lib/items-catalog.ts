// Tipo do item geral
export type ItemType = 
  | 'medical'      // Kits médicos e suprimentos
  | 'investigation' // Equipamentos de investigação
  | 'communication' // Comunicadores e eletrônicos
  | 'field'        // Itens de campo e ferramentas
  | 'paranormal'   // Itens paranormais e rituais
  | 'survival'     // Sobrevivência e utilidades
  | 'document';    // Documentos e credenciais

// Interface completa para item do catálogo
export interface CatalogItem {
  id: string;
  name: string;
  type: ItemType;
  category: '0' | 'I' | 'II' | 'III' | 'IV';
  spaces: number;
  description: string;
  effect?: string; // Efeito mecânico do item
  uses?: number; // Número de usos (se aplicável)
  consumable?: boolean; // Se é consumível
}

